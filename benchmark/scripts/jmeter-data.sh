#!/usr/bin/env bash
# Export the input data for the JMeter plans from the seeded template database.
# Both working databases are copies of the same deterministic seed, so the files
# are shared by the Laravel and NestJS runs. Re-run after scripts/db-setup.sh.
#
# Output (jmeter/data/):
#   ranges.properties          page counts and id ranges, loaded with `jmeter -q`
#   available_menu_items.csv   ids with is_available = true (EP7 must not pick the others)
#
# Usage: scripts/jmeter-data.sh
set -euo pipefail

cd "$(dirname "$0")/.."

PER_PAGE=20
out=jmeter/data
mkdir -p "$out"

query() {
    docker compose exec -T postgres sh -c \
        'psql -U "$POSTGRES_USER" -d laravel_app_template -v ON_ERROR_STOP=1 -X -q -A -t -F ","' <<<"$1"
}

docker compose up -d --wait postgres >/dev/null 2>&1

IFS=, read -r tables_count menu_available orders_count orders_max dishes_max < <(query "
SELECT (SELECT COUNT(*) FROM tables),
       (SELECT COUNT(*) FROM menu_items WHERE is_available),
       (SELECT COUNT(*) FROM orders),
       (SELECT MAX(id) FROM orders),
       (SELECT MAX(id) FROM dishes);
")

# A random order id is only safe if the ids have no gaps (otherwise EP8 would hit 404s).
if [ "$orders_count" != "$orders_max" ]; then
    echo "ERROR: orders ids are not contiguous (COUNT=${orders_count}, MAX(id)=${orders_max})." >&2
    exit 1
fi

pages() { echo $(( ($1 + PER_PAGE - 1) / PER_PAGE )); }

cat >"$out/ranges.properties" <<EOF
# Generated by scripts/jmeter-data.sh from laravel_app_template; do not edit.
ep1.pages=$(pages "$tables_count")
ep2.pages=$(pages "$menu_available")
orders.max=${orders_max}
dishes.max=${dishes_max}
EOF

{
    echo "menu_item_id"
    query "SELECT id FROM menu_items WHERE is_available ORDER BY id;"
} >"$out/available_menu_items.csv"

echo "Wrote ${out}/ranges.properties:"
grep -v '^#' "$out/ranges.properties"
echo "Wrote ${out}/available_menu_items.csv ($((menu_available)) ids)."
